// СРОКИ ХРАНЕНИЯ: один планировщик на все автоочистки.
//
// Данных с собственным сроком в системе уже несколько (журнал согласий,
// заявки на регистрацию), и у каждой была бы своя копия одного и того же
// таймера. Копия таймера — это место, где одна из очисток однажды тихо
// перестанет запускаться.
//
// Отдельного крона нет намеренно: процесс Node один, better-sqlite3
// синхронный, второй писатель дал бы «database is locked».

/**
 * Запускает job сразу и дальше раз в сутки. unref() — таймер не держит процесс
 * живым и не мешает тестам. Падение одной очистки не роняет остальные и не
 * роняет сервер: срок хранения важен, но не важнее работающего сайта.
 */
export function scheduleDailyPurge(name, job, { intervalMs = 24 * 60 * 60 * 1000 } = {}) {
  const run = () => {
    try {
      const removed = job();
      if (removed) console.log(`[retention] ${name}: удалено записей — ${removed}`);
    } catch (err) {
      console.error(`[retention] ${name}: автоочистка не удалась`, err);
    }
  };
  run();
  const timer = setInterval(run, intervalMs);
  timer.unref();
  return timer;
}
