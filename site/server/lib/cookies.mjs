/**
 * РЕЕСТР COOKIE — единственный источник правды о том, что сайт кладёт в браузер.
 *
 * Зачем отдельный модуль, а не комментарий в политике: согласие на cookie по
 * 152-ФЗ требуется НЕ на все подряд, а только на необязательные. Пока таких нет,
 * баннер согласия — вредная формальность: он приучает жать «принять» вслепую и
 * спрашивает разрешение на то, чего мы не делаем. Но в день, когда на сайт
 * добавят счётчик, забыть про согласие нельзя — штраф и предписание.
 *
 * Решение: показ баннера ПРОИЗВОДЕН от этого списка, а не от отдельного флага,
 * который можно забыть переключить. Появилась строка с category !== 'necessary'
 * -> needsConsent() сам вернёт true.
 *
 * ПРАВИЛО ДЛЯ БУДУЩЕГО: любая новая cookie обязана быть описана здесь. Cookie,
 * которой нет в реестре, не должно существовать — раздел 8 Политики строится
 * из этого же списка, и расхождение между кодом и политикой станет невозможным.
 */

/** Категории. Необходимые согласия не требуют (ч. 1 ст. 6 152-ФЗ — обработка
 *  для исполнения договора/предоставления сервиса, о котором просит сам субъект). */
export const CATEGORIES = {
  necessary: {
    key: 'necessary',
    title: 'Строго необходимые',
    description:
      'Нужны для входа в личный кабинет и защиты форм от подделки запросов. ' +
      'Без них сайт не работает, поэтому отключить их нельзя и согласия они не требуют.',
    canDisable: false,
  },
  analytics: {
    key: 'analytics',
    title: 'Аналитика',
    description: 'Помогают понять, какие разделы читают. Ставятся только с вашего согласия.',
    canDisable: true,
  },
  other: {
    key: 'other',
    title: 'Прочие',
    description: 'Всё остальное. Ставятся только с вашего согласия.',
    canDisable: true,
  },
};

/**
 * Фактический состав. На 23.08.2026 — одна запись.
 * Проверяется тестом приёмки: браузер не должен получить ни одной cookie,
 * которой здесь нет.
 */
export const COOKIE_REGISTRY = [
  {
    name: 'ftso.sid',
    category: 'necessary',
    purpose: 'Идентификатор сессии: вход в личный кабинет и в админку, защита форм (CSRF).',
    lifetime: '12 часов с последнего действия',
    setBy: 'Сайт ФТСО',
  },
];

/** Технические хранилища, которые не являются cookie, но их состав тоже полагается раскрыть. */
export const LOCAL_STORAGE_REGISTRY = [
  {
    name: 'ftso-theme',
    purpose: 'Выбранное оформление (светлое/тёмное). На сервер не передаётся.',
    lifetime: 'До очистки данных сайта в браузере',
  },
];

/** Cookie, требующие согласия (всё, кроме строго необходимых). */
export function optionalCookies() {
  return COOKIE_REGISTRY.filter((c) => CATEGORIES[c.category]?.canDisable);
}

/**
 * Нужен ли баннер согласия ПРЯМО СЕЙЧАС.
 * Сейчас false. Станет true само, как только в реестр добавят необязательную cookie.
 */
export function needsCookieConsent() {
  return optionalCookies().length > 0;
}

/** Категории, реально присутствующие в реестре — для страницы настроек. */
export function activeCategories() {
  const used = new Set(COOKIE_REGISTRY.map((c) => c.category));
  return [...used].map((k) => CATEGORIES[k]).filter(Boolean);
}

/** Состав по категориям — для раздела 8 Политики и страницы настроек. */
export function registryByCategory() {
  return activeCategories().map((cat) => ({
    ...cat,
    cookies: COOKIE_REGISTRY.filter((c) => c.category === cat.key),
  }));
}
